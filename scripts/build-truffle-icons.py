#!/usr/bin/env python3
"""Builds the Truffle Vault's boar art from android-native/art/icons (the source grids and truffles.json).

For each icon id it writes, under android-native/app/src:
  main/res/drawable-nodpi/truffle_<id>.webp          the in-app avatar (256 px, the art inside the grid tile's frame)
  main/java/.../appearance/TruffleArt.kt             id -> avatar and launcher alias, no name lookups at run time
and the launcher icons, which the app only builds in when the flag boar.truffleLauncherIcons is on (build.gradle.kts):
  launcherIcons/res/drawable-nodpi/ic_fg_<id>.webp   the launcher icon's foreground (432 px, art in the 72/108 area)
  launcherIcons/res/mipmap-anydpi-v26/ic_launcher_<id>.xml  the adaptive icon (background color from the tile's edge)
  launcherIcons/res/values/truffle_colors.xml        those background colors
  launcherIcons/AndroidManifest.xml                  one disabled <activity-alias> per icon, between the truffle markers

A 1024 px file at art/icons/hires/<id>.png or .webp (no frame) replaces that icon's grid crop: drop it in and run again.

  python3 -I scripts/build-truffle-icons.py                 # write
  python3 -I scripts/build-truffle-icons.py --sheet out.png # also a contact sheet of every avatar
  python3 -I scripts/build-truffle-icons.py --check         # exit 1 if the generated files are out of date
"""
import io
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageStat

ROOT = Path(__file__).resolve().parent.parent / "android-native"
ART = ROOT / "art" / "icons"
MAIN = ROOT / "app" / "src" / "main"
RES = MAIN / "res"
LAUNCHER = ROOT / "app" / "src" / "launcherIcons"
LRES = LAUNCHER / "res"
KT = MAIN / "java" / "team" / "sopa" / "boar" / "appearance" / "TruffleArt.kt"
MANIFEST = LAUNCHER / "AndroidManifest.xml"
START, END = "<!-- truffle-aliases:start (generated by scripts/build-truffle-icons.py) -->", "<!-- truffle-aliases:end -->"

AVATAR_PX = 256
FG_CANVAS = 432  # 108 dp at xxxhdpi
FG_ART = 300  # a little past the 288 px (72 dp) the launcher mask shows, so no background seam shows at the edges
FRAME_INSET = 0.085  # share of the tile on each side taken by the baked-in rounded frame


def art_for(icon, grids):
    for ext in ("png", "webp"):
        hires = ART / "hires" / f"{icon['id']}.{ext}"
        if hires.exists():
            return Image.open(hires).convert("RGB")
    g = grids[icon["grid"]]
    (x0, x1), (y0, y1) = g["cols"][icon["col"]], g["rows"][icon["row"]]
    side = min(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    inner = side * (1 - 2 * FRAME_INSET)
    box = tuple(round(v) for v in (cx - inner / 2, cy - inner / 2, cx + inner / 2, cy + inner / 2))
    return g["image"].crop(box)


def edge_color(img):
    w, h = img.size
    band = max(2, w // 20)
    strips = [img.crop((0, 0, w, band)), img.crop((0, h - band, w, h)), img.crop((0, 0, band, h)), img.crop((w - band, 0, w, h))]
    means = [ImageStat.Stat(s).mean for s in strips]
    return tuple(round(sum(m[i] for m in means) / len(means)) for i in range(3))


def webp(img, quality=88):
    buf = io.BytesIO()
    img.save(buf, "WEBP", quality=quality, method=6)
    return buf.getvalue()


def build():
    spec = json.loads((ART / "truffles.json").read_text())
    grids = {k: dict(v, image=Image.open(ART / v["file"]).convert("RGB")) for k, v in spec["grids"].items()}
    files, colors, avatars = {}, [], []
    for icon in spec["icons"]:
        i = icon["id"]
        art = art_for(icon, grids)
        avatar = art.resize((AVATAR_PX, AVATAR_PX), Image.LANCZOS)
        avatars.append((i, avatar))
        files[RES / "drawable-nodpi" / f"truffle_{i}.webp"] = webp(avatar)
        fg = Image.new("RGBA", (FG_CANVAS, FG_CANVAS), (0, 0, 0, 0))
        off = (FG_CANVAS - FG_ART) // 2
        fg.paste(art.resize((FG_ART, FG_ART), Image.LANCZOS), (off, off))
        files[LRES / "drawable-nodpi" / f"ic_fg_{i}.webp"] = webp(fg)
        r, g, b = edge_color(art)
        colors.append(f'    <color name="ic_bg_{i}">#{r:02X}{g:02X}{b:02X}</color>')
        files[LRES / "mipmap-anydpi-v26" / f"ic_launcher_{i}.xml"] = (
            '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/build-truffle-icons.py. -->\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            f'    <background android:drawable="@color/ic_bg_{i}" />\n'
            f'    <foreground android:drawable="@drawable/ic_fg_{i}" />\n</adaptive-icon>\n'
        ).encode()
    files[LRES / "values" / "truffle_colors.xml"] = (
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/build-truffle-icons.py: launcher icon backgrounds. -->\n<resources>\n'
        + "\n".join(colors) + "\n</resources>\n"
    ).encode()
    ids = [icon["id"] for icon in spec["icons"]]
    entries = "\n".join(f'        "{i}" to Art(R.drawable.truffle_{i}, "{alias(i)}"),' for i in ids)
    files[KT] = (
        "// Generated by scripts/build-truffle-icons.py from android-native/art/icons/truffles.json. Do not edit by hand.\n"
        "package team.sopa.boar.appearance\n\nimport team.sopa.boar.R\n\n"
        "/** Each boar's in-app avatar and launcher alias (a class name relative to the code's namespace; the alias only exists\n"
        " * when the launcher-icons flag is on). */\n"
        "object TruffleArt {\n    data class Art(val avatar: Int, val alias: String)\n\n"
        f"    val byId: Map<String, Art> = linkedMapOf(\n{entries}\n    )\n}}\n"
    ).encode()
    aliases = "\n".join(
        f'        <activity-alias android:name="{alias(i)}" android:targetActivity=".MainActivity" android:enabled="false"\n'
        f'            android:exported="true" android:icon="@mipmap/ic_launcher_{i}" android:roundIcon="@mipmap/ic_launcher_{i}">\n'
        '            <intent-filter><action android:name="android.intent.action.MAIN" /><category android:name="android.intent.category.LAUNCHER" /></intent-filter>\n'
        "        </activity-alias>"
        for i in ids
    )
    manifest = MANIFEST.read_text()
    a, b = manifest.index(START), manifest.index(END)
    files[MANIFEST] = (manifest[: a + len(START)] + "\n" + aliases + "\n        " + manifest[b:]).encode()
    return files, avatars


def alias(i):
    return ".Launcher_" + i


def sheet(avatars, path):
    cols, cell = 8, 140
    rows = (len(avatars) + cols - 1) // cols
    out = Image.new("RGB", (cols * cell, rows * (cell + 18)), (20, 22, 26))
    d = ImageDraw.Draw(out)
    for n, (i, img) in enumerate(avatars):
        x, y = (n % cols) * cell, (n // cols) * (cell + 18)
        out.paste(img.resize((cell - 12, cell - 12), Image.LANCZOS), (x + 6, y + 6))
        d.text((x + 6, y + cell - 4), i, fill=(220, 220, 220))
    out.save(path)


def main(argv):
    files, avatars = build()
    if "--check" in argv:
        stale = [str(p) for p, data in files.items() if not p.exists() or p.read_bytes() != data]
        if stale:
            print("out of date:\n  " + "\n  ".join(stale))
            return 1
        print(f"up to date ({len(avatars)} icons)")
        return 0
    for p, data in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    if "--sheet" in argv:
        sheet(avatars, argv[argv.index("--sheet") + 1])
    print(f"wrote {len(avatars)} icons ({sum(len(d) for d in files.values()) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
