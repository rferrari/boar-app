/** A Boar Labs plugin folder: src/labs/plugins/<folder>/plugin.properties (folders starting with _ are templates). */
/** [review]: under review (review=true), so its engine (jniLibs) stays out of the APK, whatever the build. */
class LabPluginDir(val dir: File, val id: String, val obj: String?, val classified: String?, val order: Int, val review: Boolean)

val labPlugins: List<LabPluginDir> = file("src/labs/plugins").listFiles().orEmpty()
    .filter { it.isDirectory && !it.name.startsWith("_") && it.resolve("plugin.properties").isFile }
    .map { dir ->
        val p = Properties().apply { dir.resolve("plugin.properties").reader(Charsets.UTF_8).use { load(it) } }
        val id = p.getProperty("id")?.trim() ?: error("${dir.name}/plugin.properties: no id")
        require(id == dir.name) { "${dir.name}/plugin.properties: id=$id must match the folder name" }
        val obj = p.getProperty("object")?.trim()
        val classified = p.getProperty("classified")?.trim()
        // Both: a working lab kept as a teaser in normal builds, built as itself with -Pboar.labs.declassify=<id> (Oct 24).
        require(obj != null || classified != null) { "${dir.name}/plugin.properties: set object=, classified=, or both" }
        LabPluginDir(dir, id, obj, classified, p.getProperty("order")?.trim()?.toInt() ?: 100, p.getProperty("review")?.trim()?.toBoolean() ?: false)
    }
    .sortedWith(compareBy({ it.order }, { it.id }))

// The registry the app reads (LabRegistry.ALL), written from the plugin folders: no shared list to edit.
val labsRegistryDir = layout.buildDirectory.dir("generated/labsRegistry")
val generateLabsRegistry by tasks.registering {
    // Labs a builder brings out of classified: -Pboar.labs.declassify=dailyQuiz (comma-separated ids).
    val declassified = (providers.gradleProperty("boar.labs.declassify").orNull ?: "").split(',').map { it.trim() }.filter { it.isNotEmpty() }.toSet()
    val entries = labPlugins.map { p ->
        // A classified lab with code keeps it behind the teaser: a leak (the Labs easter egg) unlocks it (ClassifiedLab.inner).
        if (p.classified != null && (p.obj == null || p.id !in declassified)) "ClassifiedLab(\"${p.id}\", \"${p.classified}\"${if (p.obj != null) ", ${p.obj}" else ""})" else p.obj!!
    }
    inputs.property("entries", entries)
    outputs.dir(labsRegistryDir)
    doLast {
        val out = labsRegistryDir.get().asFile.resolve("team/sopa/boar/labs/GeneratedLabs.kt")
        out.parentFile.mkdirs()
        out.writeText("package team.sopa.boar.labs\n\n// Generated by app/build.gradle.kts from src/labs/plugins/*/plugin.properties. Don't edit.\n" +
            "internal val GENERATED_LABS: List<LabPlugin> = listOf(\n" + entries.joinToString("") { "    $it,\n" } + ")\n")
    }
}
tasks.named("preBuild") { dependsOn(generateLabsRegistry) }

android {
    namespace = "team.sopa.boar"
    compileSdk = 36
    // The NDK's strip tool for the engine's libraries: without it they ship with their debug symbols (77 MB libllama-common).
    ndkVersion = "27.1.12297006"

    // The Supabase URL and publishable key the Expo app reads (EXPO_PUBLIC_* in the repo's .env, never committed).
    // Without them the build has no Share button, as the Expo app.
    val env = rootProject.file("../.env").takeIf { it.isFile }?.readLines().orEmpty()
        .mapNotNull { l -> l.split("=", limit = 2).takeIf { it.size == 2 }?.let { it[0].trim() to it[1].trim().trim('"') } }.toMap()

    // FLAG: the Truffle Vault's boars as the launcher icon (src/launcherIcons: activity aliases and icons). Off by default:
    // the boars stay inside the app. On with boar.truffleLauncherIcons=true (gradle.properties or -P) or
    // BOAR_TRUFFLE_LAUNCHER_ICONS=true (the repo's .env or the environment).
    val truffleLauncherIcons = (providers.gradleProperty("boar.truffleLauncherIcons").orNull
        ?: env["BOAR_TRUFFLE_LAUNCHER_ICONS"] ?: System.getenv("BOAR_TRUFFLE_LAUNCHER_ICONS"))?.trim()?.toBoolean() ?: false
    // You read the build file: there's an EXPERIMENTAL block at the bottom of Advanced tweaks (Boar Labs, Boar Avatars),
    // shown only in builds with EXPERIMENTAL_FEATURES=true in the repo's .env (or the environment, or -Pboar.experimentalFeatures=true).
    // Without it the switches never show and both stay off. The labs' executables (each plugin's jniLibs: the image lab's
    // sd-cli from scripts/build-sd-cli.sh, about 31 MB; the bmoe and colibri engines from scripts/build-lab-engines.sh,
    // about 8 MB) ship only with it, unless boar.labs.executables=false (boar.labs.imageEngine=false, its old name).
    val experimental = (providers.gradleProperty("boar.experimentalFeatures").orNull ?: env["EXPERIMENTAL_FEATURES"] ?: System.getenv("EXPERIMENTAL_FEATURES"))?.trim()?.toBoolean() ?: false
    val labsExecutables = experimental && ((providers.gradleProperty("boar.labs.executables").orNull ?: providers.gradleProperty("boar.labs.imageEngine").orNull)?.trim()?.toBoolean() ?: true)
    // Uncensored and adult models (HfQuery.uncensored) are hidden from Discover GGUF models unless ALLOW_UNCENSORED_MODELS=true
    // (.env, the environment, or -Pboar.allowUncensoredModels=true).
    val allowUncensored = (providers.gradleProperty("boar.allowUncensoredModels").orNull ?: env["ALLOW_UNCENSORED_MODELS"] ?: System.getenv("ALLOW_UNCENSORED_MODELS"))?.trim()?.toBoolean() ?: false
    // Settings → Advanced tweaks → Debug log only exists in builds with ALLOW_DEBUG_LOG=true in the repo's .env (or the
    // environment, or -Pboar.allowDebugLog=true). Without it there is no switch and nothing is ever logged.
    val allowDebugLog = (providers.gradleProperty("boar.allowDebugLog").orNull ?: env["ALLOW_DEBUG_LOG"] ?: System.getenv("ALLOW_DEBUG_LOG"))?.trim()?.toBoolean() ?: false
    // The menu's memory and storage bars (Settings → Advanced tweaks, off by default) exist unless ALLOW_DRAWER_STATS=false
    // in the repo's .env (or the environment, or -Pboar.allowDrawerStats=false); then they never show.
    val allowDrawerStats = (providers.gradleProperty("boar.allowDrawerStats").orNull ?: env["ALLOW_DRAWER_STATS"] ?: System.getenv("ALLOW_DRAWER_STATS"))?.trim()?.toBoolean() ?: true
    // Evaluation in the menu: for builders who run and submit evaluations. SHOW_EVAL_IN_MENU in the repo's .env (or the
    // environment, or -Pboar.showEvalInMenu); off by default, Labs builds included (Oct 15: it's a builder's tool, not a
    // menu entry). Either way the screen stays reachable from Settings → Advanced tweaks, and the USB runner (eval:device)
    // never needs it.
    val showEvalInMenu = (providers.gradleProperty("boar.showEvalInMenu").orNull ?: env["SHOW_EVAL_IN_MENU"] ?: System.getenv("SHOW_EVAL_IN_MENU"))?.trim()?.toBoolean() ?: false
    // Sharing evaluation results with BOAR's server is off unless EVAL_SHARING=true (.env, the environment, or
    // -Pboar.evalSharing=true). Off, the server's address and key aren't built in at all: no Share button, and runs and
    // their files stay on the phone. In two weeks after launch only the team shared a run (Oct 19).
    val evalSharing = (providers.gradleProperty("boar.evalSharing").orNull ?: env["EVAL_SHARING"] ?: System.getenv("EVAL_SHARING"))?.trim()?.toBoolean() ?: false
    defaultConfig {
        buildConfigField("boolean", "SHOW_EVAL_IN_MENU", "$showEvalInMenu")
        buildConfigField("boolean", "ALLOW_DEBUG_LOG", "$allowDebugLog")
        buildConfigField("boolean", "ALLOW_DRAWER_STATS", "$allowDrawerStats")
        buildConfigField("boolean", "ALLOW_UNCENSORED_MODELS", "$allowUncensored")
        buildConfigField("boolean", "TRUFFLE_LAUNCHER_ICONS", "$truffleLauncherIcons")
        buildConfigField("boolean", "EXPERIMENTAL_FEATURES", "$experimental")
        // Lab ids to leave out of the grid (labs/LabPlugin.kt), e.g. boar.labs.hide=bigBrain,signboard.
        val labsHide = providers.gradleProperty("boar.labs.hide").orNull ?: ""
        buildConfigField("String", "LABS_HIDE", "\"${labsHide.replace("\"", "")}\"")
        buildConfigField("String", "SUPABASE_URL", "\"${if (evalSharing) env["EXPO_PUBLIC_SUPABASE_URL"] ?: "" else ""}\"")
        buildConfigField("String", "SUPABASE_PUBLISHABLE_KEY", "\"${if (evalSharing) env["EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY"] ?: "" else ""}\"")
        // The release keeps the Expo app's id and key, so it installs over v1.1.x with its models.
        applicationId = "team.sopa.aoair"
        // A second install beside BOAR (its own data): -Pboar.appIdSuffix=.labs gives team.sopa.aoair.labs, labelled
        // "BOAR Labs", from the same release build.
        val appIdSuffix = (findProperty("boar.appIdSuffix") as String?)?.takeIf { it.isNotBlank() }
        appIdSuffix?.let { applicationIdSuffix = it }
        manifestPlaceholders["appLabel"] = if (appIdSuffix != null) "BOAR Labs" else "@string/app_name"
        minSdk = 26
        targetSdk = 36
        versionCode = 4
        // The release name comes from the build (-Pboar.versionName=2.0.0 for a release), the commit and date from git, so
        // About always says exactly which code this APK is.
        versionName = (findProperty("boar.versionName") as String?)?.takeIf { it.isNotBlank() } ?: "2.0.0-dev"
        val gitSha = runCatching { providers.exec { commandLine("git", "rev-parse", "--short=8", "HEAD"); isIgnoreExitValue = true }.standardOutput.asText.get().trim() }.getOrNull().orEmpty()
        val gitDirty = runCatching { providers.exec { commandLine("git", "status", "--porcelain", "--untracked-files=no", "--ignore-submodules=all"); isIgnoreExitValue = true }.standardOutput.asText.get().isNotBlank() }.getOrDefault(false)
        buildConfigField("String", "GIT_SHA", "\"${gitSha}${if (gitDirty) "+" else ""}\"")
        buildConfigField("String", "BUILD_DATE", "\"${LocalDate.now()}\"")
        ndk { abiFilters += listOf("arm64-v8a") }
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }
    // The Expo app's upload key, named in ~/.gradle/gradle.properties (never in the repo), as plugins/withReleaseSigning.js
    // reads it. Without it the release is debug-signed, which can't install over a store or release build of BOAR.
    val storeFile = providers.gradleProperty("BOAR_UPLOAD_STORE_FILE").orNull
    signingConfigs {
        if (storeFile != null) create("release") {
            this.storeFile = file(storeFile)
            storePassword = providers.gradleProperty("BOAR_UPLOAD_STORE_PASSWORD").get()
            keyAlias = providers.gradleProperty("BOAR_UPLOAD_KEY_ALIAS").get()
            keyPassword = providers.gradleProperty("BOAR_UPLOAD_KEY_PASSWORD").get()
        }
    }
    buildTypes {
        debug {
            // Development builds install beside the current BOAR, never over it.
            applicationIdSuffix = ".native"
            versionNameSuffix = "-native"
        }
        // A throwaway install for the on-device tests that wipe data (first-run setup, Purge All Data), so they never
        // touch the debug app someone is using.
        create("devtest") {
            initWith(getByName("debug"))
            applicationIdSuffix = ".devtest"
            versionNameSuffix = "-devtest"
            matchingFallbacks += listOf("debug")
        }
        release {
            isMinifyEnabled = false
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures { compose = true; buildConfig = true }
    // Instrumented tests run against the throwaway devtest install (./gradlew :app:assembleDevtestAndroidTest).
    testBuildType = "devtest"
    packaging { jniLibs { useLegacyPackaging = true } }
    if (truffleLauncherIcons) {
        // Merged over main for every build type: the launcher entry moves to the aliases.
        for (type in listOf("debug", "release", "devtest")) sourceSets[type].manifest.srcFile("src/launcherIcons/AndroidManifest.xml")
        sourceSets["main"].res.srcDir("src/launcherIcons/res")
    }
    // Boar Labs: the framework (src/labs/java, res) and every plugin folder under src/labs/plugins, found here, so a
    // plugin is one folder and nothing else (docs/PLUGINS.md). A plugin's jniLibs (gitignored executables named lib*.so,
    // e.g. sd-cli or bmoe-cli, installed runnable in nativeLibraryDir) ship only in experimental builds, and never for a
    // lab under review (Oct 24): Play Protect blocks an APK whose executables it doesn't trust, so only the ones in use go.
    sourceSets["main"].java.srcDir("src/labs/java")
    sourceSets["main"].res.srcDir("src/labs/res")
    sourceSets["main"].java.srcDir(labsRegistryDir)
    for (plugin in labPlugins) {
        sourceSets["main"].java.srcDir(plugin.dir.resolve("java"))
        sourceSets["main"].res.srcDir(plugin.dir.resolve("res"))
        if (labsExecutables && !plugin.review) sourceSets["main"].jniLibs.srcDir(plugin.dir.resolve("jniLibs"))
    }
}

